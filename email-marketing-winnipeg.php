                <details class="faq-item">
                    <summary class="faq-question">Is email marketing still worth it for a small business?</summary>
                    <p class="faq-answer">Yes &mdash; and arguably more than ever. Social platforms change their algorithms and your reach with them. Your email list is an asset you own outright. People who signed up to hear from you actually want to hear from you, which is a different relationship than a social follower scrolling past your post. For small businesses with limited marketing budgets, it remains one of the highest-ROI channels available.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">How often should I be emailing my list?</summary>
                    <p class="faq-answer">For most small businesses, once or twice a month is a solid starting point &mdash; enough to stay visible without wearing out your welcome. The bigger mistake is usually emailing too rarely, not too often. If someone hasn&rsquo;t heard from you in six months, they&rsquo;ve forgotten who you are. Consistency matters more than frequency.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">What should I actually write about?</summary>
                    <p class="faq-answer">More than coupons. The emails people open are the ones that give them something &mdash; a useful tip, a story, an early heads up, a behind-the-scenes look. Promotional content works when it&rsquo;s earned by the value around it. A good mix is roughly 80% useful or interesting, 20% ask.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">What platform should I use?</summary>
                    <p class="faq-answer">Depends on what you&rsquo;re selling and how sophisticated your flows need to be. Klaviyo is the strongest option for ecommerce and Shopify stores. Mailchimp works fine for simpler service businesses. I&rsquo;ll recommend what actually fits your situation rather than defaulting to whatever&rsquo;s easiest for me to set up.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">Do I need to worry about CASL compliance in Canada?</summary>
                    <p class="faq-answer">Yes. Canada&rsquo;s Anti-Spam Legislation requires explicit consent before sending commercial email &mdash; you can&rsquo;t just add people to your list without permission. It&rsquo;s stricter than US CAN-SPAM rules. Getting this right from the start is important; retrofitting a non-compliant list later is painful. I build CASL-compliant opt-in flows as a standard part of any email setup.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">My list is small. Is it even worth starting?</summary>
                    <p class="faq-answer">A small engaged list outperforms a large disengaged one every time. Starting with 200 people who actually want to hear from you is more valuable than waiting until you have 2,000. List-building is an ongoing process &mdash; the earlier you start, the more compound value it accumulates.</p>
                </details>

