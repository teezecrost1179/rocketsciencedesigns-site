            <div class="faq-list">

                <details class="faq-item">
                    <summary class="faq-question">What&rsquo;s the difference between print design and packaging design?</summary>
                    <p class="faq-answer">Print design covers flat collateral &mdash; business cards, brochures, flyers, sell sheets, labels. Packaging design adds structural complexity: you&rsquo;re designing around a dieline, accounting for folds, seams, and bleed on a surface that curves or collapses when assembled. The design principles overlap, but packaging requires a tighter handoff with your printer and more technical prep work on the files.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">What files do I need to provide, and what will I get back?</summary>
                    <p class="faq-answer">If you have existing brand assets &mdash; logo files, brand colours, fonts &mdash; bring those. If you&rsquo;re starting fresh, we handle it. What you get back are print-ready files: press-ready PDFs with correct bleed, trim marks, and colour profiles set to CMYK. For packaging, that includes artwork built on your printer&rsquo;s dieline. I&rsquo;ll also confirm file specs directly with your printer before finalizing, since requirements vary.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">What is bleed, and why does it matter?</summary>
                    <p class="faq-answer">Bleed is a small extension of your artwork beyond the final cut line &mdash; typically 3mm or &frac18; inch &mdash; that accounts for the slight mechanical variation in cutting equipment. Without it, you risk a thin white edge appearing on the finished piece where the cut landed fractionally off. It&rsquo;s a technical detail that&rsquo;s easy to get right at the design stage and costly to fix after the fact.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">Do I need to find my own printer, or can you help with that?</summary>
                    <p class="faq-answer">You source the printer &mdash; I&rsquo;m not a print broker and don&rsquo;t take a cut on production. What I can do is help you ask the right questions, review printer specs before files are submitted, and flag anything that might cause delays or reprints. If you already have a printer relationship, I&rsquo;ll work to their requirements directly.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">Does my packaging need to be bilingual?</summary>
                    <p class="faq-answer">For consumer products sold in Canada, the short answer is usually yes. Federal labelling regulations require English and French on most packaged goods &mdash; product identity, net quantity, and dealer name at minimum. The specifics depend on your product category, whether you&rsquo;re selling provincially or nationally, and your distribution channels. I&rsquo;ll flag the requirements during the brief, but you should confirm the details with a regulatory consultant or the CFIA for anything going to retail at scale.</p>
                </details>

                <details class="faq-item">
                    <summary class="faq-question">How long does a print or packaging project take?</summary>
                    <p class="faq-answer">Design turnaround is typically one to two weeks depending on complexity and how quickly feedback comes back. That&rsquo;s design only &mdash; print production time is separate and depends entirely on your printer and whether the files are approved clean on the first pass. Getting the files right before submission is the fastest way to keep the overall timeline on track.</p>
                </details>

